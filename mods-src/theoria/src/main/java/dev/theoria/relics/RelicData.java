package dev.theoria.relics;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import dev.theoria.Theoria;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import net.minecraft.resources.Identifier;
import net.minecraft.world.entity.ai.attributes.AttributeModifier;
import net.minecraft.world.item.Rarity;

/**
 * The relic table (Faz 12), read from the jar: {@code theoria/relics.json}, generated by generator/relics.py from data/relics.csv + data/relic_sources.csv — the single source of every
 * relic number, name and source. Read from the classpath and not through the datapack reload because items are registered before any datapack exists and the client needs the same
 * numbers for tooltips (the same reason as catalysts/default.json). A new relic = a CSV row; Java only knows the effect {@link Kind}s.
 */
public final class RelicData {
    public static final String RESOURCE = "/theoria/relics.json";

    public enum Kind {
        EFFECT, ATTRIBUTE, MAGNET, FOOD, REPAIR, IMMUNE, REVEAL, SURVIVE;

        static Kind of(String name) {
            return valueOf(name.toUpperCase(Locale.ROOT));
        }
    }

    /** One attribute modifier a relic carries while worn ({@code attribute} kind). */
    public record Mod(String attribute, AttributeModifier.Operation op, double amount) {}

    /** "This relic can come from {@code source} with relative {@code weight}". */
    public record Source(String source, int weight) {}

    /** A row of data/relic_sources.csv: a chest table or a boss the relic loot modifiers hook. */
    public record SourceDef(String id, boolean boss, String target, double chance) {}

    public record Def(int index, String id, String slot, String rarity, Kind kind, Map<String, Object> params, List<Mod> mods, List<Source> sources) {
        public Identifier itemId() {
            return Theoria.id("relic/" + id);
        }

        public String nameKey() {
            return "item.theoria.relic." + id;
        }

        public double num(String key) {
            Object value = params.get(key);
            if (!(value instanceof Number n)) throw new IllegalStateException("relic " + id + ": missing numeric parameter " + key);
            return n.doubleValue();
        }

        public String str(String key) {
            Object value = params.get(key);
            if (!(value instanceof String s)) throw new IllegalStateException("relic " + id + ": missing text parameter " + key);
            return s;
        }

        /** Vanilla {@link Rarity} for the name colour: common/uncommon/rare as is, legendary = epic. */
        public Rarity vanillaRarity() {
            return switch (rarity) {
                case "uncommon" -> Rarity.UNCOMMON;
                case "rare" -> Rarity.RARE;
                case "legendary" -> Rarity.EPIC;
                default -> Rarity.COMMON;
            };
        }

        /** The attribute modifier id of modifier number {@code n}: one id per relic, so wearing the same relic twice never doubles it. */
        public Identifier modifierId(int n) {
            return Theoria.id("relic/" + id + "/" + n);
        }
    }

    public record Table(List<Def> relics, Map<String, Def> byId, List<SourceDef> sources) {}

    private static Table table;

    private RelicData() {}

    public static synchronized Table table() {
        if (table == null) table = load();
        return table;
    }

    public static List<Def> all() {
        return table().relics();
    }

    public static Def get(String id) {
        return table().byId().get(id);
    }

    public static Table load() {
        try (InputStream in = RelicData.class.getResourceAsStream(RESOURCE)) {
            if (in == null) throw new IllegalStateException("Missing jar resource " + RESOURCE + " (python3 -I generator/relics.py)");
            JsonObject root = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
            List<Def> relics = new ArrayList<>();
            Map<String, Def> byId = new LinkedHashMap<>();
            for (JsonElement element : root.getAsJsonArray("relics")) {
                JsonObject r = element.getAsJsonObject();
                Map<String, Object> params = new LinkedHashMap<>();
                for (Map.Entry<String, JsonElement> p : r.getAsJsonObject("params").entrySet()) {
                    params.put(p.getKey(), p.getValue().getAsJsonPrimitive().isNumber() ? (Object) p.getValue().getAsDouble() : p.getValue().getAsString());
                }
                List<Mod> mods = new ArrayList<>();
                for (JsonElement m : r.getAsJsonArray("mods")) {
                    JsonObject mod = m.getAsJsonObject();
                    mods.add(new Mod(mod.get("attribute").getAsString(), AttributeModifier.Operation.valueOf(mod.get("op").getAsString().toUpperCase(Locale.ROOT)), mod.get("amount").getAsDouble()));
                }
                List<Source> sources = new ArrayList<>();
                for (JsonElement s : r.getAsJsonArray("sources")) {
                    sources.add(new Source(s.getAsJsonObject().get("source").getAsString(), s.getAsJsonObject().get("weight").getAsInt()));
                }
                Def def = new Def(relics.size(), r.get("id").getAsString(), r.get("slot").getAsString(), r.get("rarity").getAsString(), Kind.of(r.get("kind").getAsString()),
                        Map.copyOf(params), List.copyOf(mods), List.copyOf(sources));
                relics.add(def);
                byId.put(def.id(), def);
            }
            List<SourceDef> sources = new ArrayList<>();
            JsonArray array = root.getAsJsonArray("sources");
            for (JsonElement element : array) {
                JsonObject s = element.getAsJsonObject();
                sources.add(new SourceDef(s.get("id").getAsString(), s.get("type").getAsString().equals("boss"), s.get("target").getAsString(), s.get("chance").getAsDouble()));
            }
            return new Table(List.copyOf(relics), java.util.Collections.unmodifiableMap(byId), List.copyOf(sources));
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
