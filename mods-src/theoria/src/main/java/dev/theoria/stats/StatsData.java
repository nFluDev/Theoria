package dev.theoria.stats;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import net.minecraft.world.entity.ai.attributes.AttributeModifier;

/**
 * The stat table and the level curve constants (docs/04 §5, docs/06 §5), read from the jar: {@code theoria/stats.json}, generated by
 * {@code tools/balance/stats.py}. Classpath and not the datapack reload on purpose, like gear.json and technical_caps.json (ADR-003): the
 * attachment codec, the items and the client screen need the same numbers before and without any datapack. Never edit the numbers here.
 */
public final class StatsData {
    public static final String RESOURCE = "/theoria/stats.json";

    /** How an effect reaches the player. */
    public enum Kind { ATTRIBUTE, EXHAUSTION, XP_PERCENT }

    /**
     * One effect of a stat: {@code value(n) = cap · n / (n + half)} for n allocated points — a soft cap with diminishing returns (Q3), first-point
     * slope {@code cap / half}.
     */
    public record Effect(String id, Kind kind, String attribute, AttributeModifier.Operation op, double cap, double half) {
        public double value(double points) {
            return points > 0 ? cap * points / (points + half) : 0.0;
        }
    }

    public record Stat(String id, List<Effect> effects) {}

    /** {@code anchors}: {level, xp} pairs ascending from {2, 55}; between two the curve is a power law in (L−1); above {@code xpKnee} (the last anchor) a level's cost grows linearly with L. */
    public record Leveling(int maxLevel, int pointsPerLevel, double[][] anchors, int xpKnee) {}

    /** Expected values the generator wrote for the self-checks: Java ≡ Python. */
    public record Cases(List<long[]> xp, List<long[]> level, List<Object[]> bonus) {}

    public record Table(Leveling leveling, String respecItem, double respecBossChance, List<Stat> stats, Map<String, Stat> byId, Cases cases) {}

    private static Table table;

    private StatsData() {}

    public static synchronized Table table() {
        if (table == null) table = load();
        return table;
    }

    public static Leveling leveling() {
        return table().leveling();
    }

    public static List<Stat> stats() {
        return table().stats();
    }

    public static Stat stat(String id) {
        return table().byId().get(id);
    }

    public static Table load() {
        try (InputStream in = StatsData.class.getResourceAsStream(RESOURCE)) {
            if (in == null) throw new IllegalStateException("Missing jar resource " + RESOURCE + " (python3 -I tools/balance/stats.py)");
            JsonObject root = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
            JsonObject lv = root.getAsJsonObject("leveling");
            JsonArray anchorJson = lv.getAsJsonArray("xp_anchors");
            double[][] anchors = new double[anchorJson.size()][];
            for (int i = 0; i < anchors.length; i++) anchors[i] = new double[] {anchorJson.get(i).getAsJsonArray().get(0).getAsDouble(), anchorJson.get(i).getAsJsonArray().get(1).getAsDouble()};
            Leveling leveling = new Leveling(lv.get("max_level").getAsInt(), lv.get("points_per_level").getAsInt(), anchors, lv.get("xp_knee").getAsInt());
            JsonObject respec = root.getAsJsonObject("respec");
            List<Stat> stats = new ArrayList<>();
            Map<String, Stat> byId = new LinkedHashMap<>();
            for (JsonElement e : root.getAsJsonArray("stats")) {
                JsonObject s = e.getAsJsonObject();
                List<Effect> effects = new ArrayList<>();
                for (JsonElement fe : s.getAsJsonArray("effects")) {
                    JsonObject f = fe.getAsJsonObject();
                    Kind kind = Kind.valueOf(f.get("kind").getAsString().toUpperCase(java.util.Locale.ROOT));
                    effects.add(new Effect(f.get("id").getAsString(), kind, f.get("attribute").getAsString(), operation(f.get("op").getAsString()),
                            f.get("cap").getAsDouble(), f.get("half").getAsDouble()));
                }
                Stat stat = new Stat(s.get("id").getAsString(), List.copyOf(effects));
                stats.add(stat);
                byId.put(stat.id(), stat);
            }
            JsonObject c = root.getAsJsonObject("cases");
            List<long[]> xp = new ArrayList<>();
            for (JsonElement e : c.getAsJsonArray("xp")) xp.add(pair(e.getAsJsonArray()));
            List<long[]> level = new ArrayList<>();
            for (JsonElement e : c.getAsJsonArray("level")) level.add(pair(e.getAsJsonArray()));
            List<Object[]> bonus = new ArrayList<>();
            for (JsonElement e : c.getAsJsonArray("bonus")) {
                JsonArray a = e.getAsJsonArray();
                bonus.add(new Object[] {a.get(0).getAsString(), a.get(1).getAsInt(), a.get(2).getAsDouble()});
            }
            return new Table(leveling, respec.get("item").getAsString(), respec.get("boss_chance").getAsDouble(), List.copyOf(stats), Map.copyOf(byId),
                    new Cases(xp, level, bonus));
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static long[] pair(JsonArray a) {
        return new long[] {a.get(0).getAsLong(), a.get(1).getAsLong()};
    }

    private static AttributeModifier.Operation operation(String name) {
        return switch (name) {
            case "add_value" -> AttributeModifier.Operation.ADD_VALUE;
            case "add_multiplied_base" -> AttributeModifier.Operation.ADD_MULTIPLIED_BASE;
            case "" -> AttributeModifier.Operation.ADD_VALUE; // non-attribute effects carry no operation
            default -> throw new IllegalArgumentException("stats.json: unknown operation " + name);
        };
    }
}
