package dev.theoria.catalyst;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import dev.theoria.Theoria;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.Identifier;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.item.enchantment.Enchantment;
import org.jspecify.annotations.Nullable;

/**
 * The catalyst table (ADR-006), read from the jar: {@code data/theoria/balance/catalysts/default.json}, generated by
 * tools/balance/catalysts.py (the single source of every number; nothing here is a balance constant). It is read from the
 * classpath and not through the datapack reload on purpose: items and the component are registered before any datapack exists
 * and the client needs the same numbers for tooltips (the same reason as gear.json and technical_caps.json, ADR-003 Karar 2).
 * A new catalyst = a row in catalysts.py.
 */
public final class CatalystData {
    public static final String RESOURCE = "/data/theoria/balance/catalysts/default.json";
    /** Targets a catalyst may name; the first three are host classes, the rest armor slots. */
    public static final List<String> ARMOR_SLOTS = List.of("head", "chest", "legs", "feet");

    public enum Kind {
        ATTRIBUTE, ENCHANT, RANGED, ERUDITION, NETHERITE;

        static Kind of(String name) {
            return switch (name) {
                case "attribute" -> ATTRIBUTE;
                case "enchant" -> ENCHANT;
                case "ranged" -> RANGED;
                case "erudition" -> ERUDITION;
                case "netherite" -> NETHERITE;
                default -> throw new IllegalArgumentException("catalysts.json: unknown kind " + name);
            };
        }

        /** Kinds that become a "virtual enchantment" (ADR-006 Karar 6). */
        public boolean virtual() {
            return this == ENCHANT || this == RANGED || this == ERUDITION;
        }
    }

    /**
     * One catalyst. {@code effects} maps a target to the attribute id (attribute kind only). {@code enchantment} is the virtual enchantment's key
     * (theoria:&lt;id&gt;) for the enchant kinds. {@code index} is the catalyst's position in the table (creative tab / lang order).
     */
    public record Def(String id, Kind kind, Set<String> targets, Map<String, String> effects, String op, String basis, double cap, int minIdx,
            String signature, boolean graded, int index, @Nullable ResourceKey<Enchantment> enchantment) {
        public Identifier identifier() {
            return Theoria.id(id);
        }

        public Identifier itemId() {
            return Theoria.id("catalyst/" + id);
        }

        public String nameKey() {
            return "item.theoria.catalyst." + id;
        }
    }

    /** Material counts of a forge recipe level (ADR-006 Karar 11). */
    public record Ladder(int level, int dust, int signature, int essence, int core) {}

    public record Innate(String tier, String host, String enchant, int level) {}

    public record Table(int levels, double[] curve, int slotBase, int slotStep, int slotMax, int platinumIdx, int platinumBonus, int tierlessSlots,
            List<Ladder> ladder, int[] netheriteCost, int netheriteMax, int netheriteDefaultCap, int enchantLevelCap, Map<String, Integer> enchantCaps,
            int[] eruditionPct, int eruditionStep, int eruditionTotalCap, Map<String, Double> aggCaps, Map<String, Def> defs, List<Innate> innate,
            List<String> tierlessItems, int tierlessIdx, Map<String, String> forge, Map<String, Map<String, double[][]>> values) {

        /** @return the value of catalyst {@code id} at {@code level} for {@code target} on a host of tier {@code idx}; NaN when that cell does not exist. */
        public double value(String id, String target, int idx, int level) {
            Map<String, double[][]> perTarget = values.get(id);
            if (perTarget == null) return Double.NaN;
            double[][] byIdx = perTarget.get(target);
            if (byIdx == null || idx < 0 || idx >= byIdx.length || byIdx[idx] == null || level < 1 || level > byIdx[idx].length) return Double.NaN;
            return byIdx[idx][level - 1];
        }

        /** The ordered list of catalysts the creative tab, lang and forge walk. */
        public List<Def> ordered() {
            return List.copyOf(defs.values());
        }
    }

    private static Table table;

    private CatalystData() {}

    public static synchronized Table table() {
        if (table == null) table = load();
        return table;
    }

    public static Table load() {
        try (InputStream in = CatalystData.class.getResourceAsStream(RESOURCE)) {
            if (in == null) throw new IllegalStateException("Missing jar resource " + RESOURCE + " (python3 -I tools/balance/catalysts.py)");
            JsonObject root = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
            JsonObject slots = root.getAsJsonObject("slots");
            List<Ladder> ladder = new ArrayList<>();
            for (JsonElement e : root.getAsJsonArray("ladder")) {
                JsonObject l = e.getAsJsonObject();
                ladder.add(new Ladder(l.get("level").getAsInt(), l.get("dust").getAsInt(), l.get("signature").getAsInt(), l.get("essence").getAsInt(), l.get("core").getAsInt()));
            }
            JsonObject neth = root.getAsJsonObject("netherite");
            Map<String, Integer> caps = new LinkedHashMap<>();
            neth.getAsJsonObject("caps").entrySet().forEach(e -> caps.put(e.getKey(), e.getValue().getAsInt()));
            JsonObject erud = root.getAsJsonObject("erudition");
            Map<String, Double> agg = new LinkedHashMap<>();
            root.getAsJsonObject("agg_caps").entrySet().forEach(e -> agg.put(e.getKey(), e.getValue().getAsDouble()));
            JsonObject values = root.getAsJsonObject("values");
            Map<String, Def> defs = new LinkedHashMap<>();
            int index = 0;
            for (JsonElement e : root.getAsJsonArray("catalysts")) {
                JsonObject c = e.getAsJsonObject();
                String id = c.get("id").getAsString();
                Kind kind = Kind.of(c.get("kind").getAsString());
                Map<String, String> effects = new LinkedHashMap<>();
                c.getAsJsonObject("effects").entrySet().forEach(x -> effects.put(x.getKey(), x.getValue().getAsString()));
                ResourceKey<Enchantment> key = kind.virtual() ? ResourceKey.create(Registries.ENCHANTMENT, Theoria.id(id)) : null;
                defs.put(id, new Def(id, kind, Set.copyOf(strings(c.getAsJsonArray("targets"))), Map.copyOf(effects), c.get("op").getAsString(), c.get("basis").getAsString(),
                        c.get("cap").getAsDouble(), c.get("min_idx").getAsInt(), c.get("signature").getAsString(), c.get("graded").getAsBoolean(), index++, key));
            }
            JsonObject tierless = root.getAsJsonObject("tierless");
            List<Innate> innate = new ArrayList<>();
            for (JsonElement e : root.getAsJsonArray("innate")) {
                JsonObject i = e.getAsJsonObject();
                innate.add(new Innate(i.get("tier").getAsString(), i.get("host").getAsString(), i.get("enchant").getAsString(), i.get("level").getAsInt()));
            }
            Map<String, String> forge = new LinkedHashMap<>();
            root.getAsJsonObject("forge").entrySet().forEach(e -> forge.put(e.getKey(), e.getValue().getAsString()));
            return new Table(root.get("levels").getAsInt(), doubles(root.getAsJsonArray("curve")), slots.get("base").getAsInt(), slots.get("step").getAsInt(),
                    slots.get("max").getAsInt(), slots.get("platinum_idx").getAsInt(), slots.get("platinum_bonus").getAsInt(), slots.get("tierless").getAsInt(),
                    List.copyOf(ladder), ints(neth.getAsJsonArray("cost")), neth.get("max").getAsInt(), neth.get("default_cap").getAsInt(), neth.get("level_cap").getAsInt(),
                    Map.copyOf(caps), ints(erud.getAsJsonArray("pct")), erud.get("step").getAsInt(), erud.get("total_cap").getAsInt(), Map.copyOf(agg), defs,
                    List.copyOf(innate), strings(tierless.getAsJsonArray("items")), tierless.get("idx").getAsInt(), Map.copyOf(forge), values(values));
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static Map<String, Map<String, double[][]>> values(JsonObject root) {
        Map<String, Map<String, double[][]>> out = new HashMap<>();
        for (var catalyst : root.entrySet()) {
            Map<String, double[][]> perTarget = new HashMap<>();
            for (var target : catalyst.getValue().getAsJsonObject().entrySet()) {
                JsonObject rows = target.getValue().getAsJsonObject();
                int size = rows.keySet().stream().mapToInt(Integer::parseInt).max().orElse(-1) + 1;
                double[][] byIdx = new double[size][];
                rows.entrySet().forEach(r -> byIdx[Integer.parseInt(r.getKey())] = doubles(r.getValue().getAsJsonArray()));
                perTarget.put(target.getKey(), byIdx);
            }
            out.put(catalyst.getKey(), perTarget);
        }
        return out;
    }

    private static List<String> strings(JsonArray array) {
        List<String> out = new ArrayList<>();
        array.forEach(e -> out.add(e.getAsString()));
        return out;
    }

    private static double[] doubles(JsonArray array) {
        double[] out = new double[array.size()];
        for (int i = 0; i < out.length; i++) out[i] = array.get(i).getAsDouble();
        return out;
    }

    private static int[] ints(JsonArray array) {
        int[] out = new int[array.size()];
        for (int i = 0; i < out.length; i++) out[i] = array.get(i).getAsInt();
        return out;
    }
}
